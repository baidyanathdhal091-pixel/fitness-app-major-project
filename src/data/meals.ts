export function getMealsByType(
  type: Meal['type'],
  dietType: DietType,
  allergies: string[],
  goal: FitnessGoal,
): Meal[] {
  return mealDatabase.filter((meal) => {
    if (meal.type !== type) return false;
    const dietMatch = meal.dietTypes.includes(dietType);
    const allergyMatch = !meal.allergens.some((a) => allergies.includes(a));
    const goalMatch = meal.suitableForGoals.includes(goal);
    return dietMatch && allergyMatch && goalMatch;
  });
}

export function getMealById(id: string): Meal | undefined {
  return mealDatabase.find((m) => m.id === id);
}
